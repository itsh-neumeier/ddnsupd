export type Key = keyof typeof en;
export const language = $state({ value: 'de' as 'de' | 'en' });
export function t(key: Key) {
  return (language.value === 'de' ? de : en)[key];
}
export function toggleLanguage() {
  language.value = language.value === 'de' ? 'en' : 'de';
  localStorage.setItem('ddnsupd-language', language.value);
  document.documentElement.lang = language.value;
}
